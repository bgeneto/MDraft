//! Generate the book-scale LaTeX benchmark fixtures from samples/latex-perf/huge.
//!
//!   node scripts/latex-perf-book.mjs           write samples/latex-perf/book{,-flat}
//!   node scripts/latex-perf-book.mjs --check   exit 1 if the committed output differs
//!
//! `huge` is about a page per chapter, too short to show how compile and viewer
//! time grow with length. Each book chapter repeats its `huge` chapter eight
//! times, with labels renamed per copy so every reference stays valid. Two
//! shapes share that content: `book/` keeps `\include`d chapter files, and
//! `book-flat/` inlines them into one `main.tex`, the single-file case where a
//! chapter-placed preview cannot help. Output is deterministic (LF, sorted
//! inputs), so the fixture hash in the baseline means something.

import { mkdirSync, readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const source = join(root, "samples", "latex-perf", "huge");
const COPIES = 8;
const CHAPTERS = 12;
const check = process.argv.includes("--check");
const header = "% Generated by scripts/latex-perf-book.mjs. Do not edit by hand.\n";

const pad = (n) => String(n).padStart(2, "0");

/** One book chapter: the huge chapter, then COPIES-1 renamed copies of its body. */
function chapter(n, markerPrefix) {
  const text = readFileSync(join(source, "chapters", `ch${pad(n)}.tex`), "utf8").replace(
    /\r\n/g,
    "\n",
  );
  const first = text.replace(
    `Performance probe paragraph C${pad(n)}.`,
    `Performance probe paragraph ${markerPrefix}${pad(n)}.`,
  );
  const body = text
    .replace(/^\\section\{[^}]*\}\n\\label\{[^}]*\}\n/, "")
    .replace(`Performance probe paragraph C${pad(n)}. `, "");
  const copies = [];
  for (let k = 2; k <= COPIES; k += 1) {
    const renamed = body
      .replace(/\b(eq|tab):ch(\d\d):/g, `$1:ch$2:k${k}:`)
      .replace(/\\subsection\{/g, "\\subsubsection{");
    copies.push(`\\subsection{Part ${k}}\n${renamed}`);
  }
  return `${first.trimEnd()}\n\n${copies.join("\n")}`.trimEnd() + "\n";
}

function main(title, body) {
  const huge = readFileSync(join(source, "main.tex"), "utf8").replace(/\r\n/g, "\n");
  const start = huge.indexOf("\\include{chapters/ch01}");
  const end = huge.indexOf("\\bibliographystyle");
  if (start < 0 || end < 0) throw new Error("huge/main.tex no longer has the expected shape");
  return (
    header +
    huge
      .slice(0, start)
      .replace("MDraft LaTeX performance: huge multi-file", `MDraft LaTeX performance: ${title}`) +
    body +
    "\n" +
    huge.slice(end)
  );
}

const outputs = new Map();
const included = [];
const flat = [];
for (let n = 1; n <= CHAPTERS; n += 1) {
  outputs.set(join("book", "chapters", `ch${pad(n)}.tex`), header + chapter(n, "B"));
  included.push(`\\include{chapters/ch${pad(n)}}`);
  flat.push(`\\clearpage\n${chapter(n, "F")}`);
}
outputs.set(join("book", "main.tex"), main("book multi-file", included.join("\n")));
outputs.set(join("book-flat", "main.tex"), main("book single file", flat.join("\n")));

const base = join(root, "samples", "latex-perf");
const binaries = [
  ["references.bib", "references.bib"],
  [join("figures", "diagram.png"), join("figures", "diagram.png")],
];
let differs = 0;
for (const [relative, content] of outputs) {
  const target = join(base, relative);
  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current !== content) {
      console.log(`differs: samples/latex-perf/${relative.replaceAll("\\", "/")}`);
      differs += 1;
    }
    continue;
  }
  mkdirSync(join(target, ".."), { recursive: true });
  writeFileSync(target, content);
}
for (const shape of ["book", "book-flat"]) {
  for (const [from, to] of binaries) {
    const target = join(base, shape, to);
    if (check) {
      if (!existsSync(target)) {
        console.log(`missing: samples/latex-perf/${shape}/${to.replaceAll("\\", "/")}`);
        differs += 1;
      }
      continue;
    }
    mkdirSync(join(target, ".."), { recursive: true });
    copyFileSync(join(source, from), target);
  }
}
if (check) {
  console.log(differs ? `${differs} file(s) differ; rerun without --check` : "book fixtures match");
  process.exit(differs ? 1 : 0);
}
console.log(`wrote ${outputs.size} files under samples/latex-perf/book{,-flat}`);
